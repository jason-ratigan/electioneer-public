-- Electoral College presidential votes are separate from popular vote snapshots and primary delegates.
-- Certified votes: National Archives, https://www.archives.gov/electoral-college/results
-- 2028 allocations: National Archives, https://www.archives.gov/electoral-college/allocation
CREATE TABLE presidential_electoral_states (
  cycle INTEGER NOT NULL CHECK (cycle >= 2000 AND cycle % 4 = 0),
  state_fips TEXT NOT NULL CHECK (state_fips ~ '^[0-9]{2}$'),
  allocated_votes SMALLINT NOT NULL CHECK (allocated_votes BETWEEN 1 AND 100),
  allocation_source_url TEXT NOT NULL,
  PRIMARY KEY (cycle, state_fips)
);

CREATE TABLE presidential_electoral_votes (
  cycle INTEGER NOT NULL,
  state_fips TEXT NOT NULL,
  recipient_name TEXT NOT NULL,
  party_abbreviation TEXT,
  votes SMALLINT NOT NULL CHECK (votes > 0),
  status TEXT NOT NULL CHECK (status IN ('unofficial', 'certified')),
  source_url TEXT NOT NULL,
  reported_at TIMESTAMPTZ,
  PRIMARY KEY (cycle, state_fips, recipient_name),
  FOREIGN KEY (cycle, state_fips)
    REFERENCES presidential_electoral_states(cycle, state_fips) ON DELETE CASCADE
);

